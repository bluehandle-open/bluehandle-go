type Locale = "zh-CN" | "en";
export type MessageKey = keyof typeof messages;
let locale: Locale = "zh-CN";

export function setLocale(language: string | undefined) {
  locale = language === "en" ? "en" : "zh-CN";
  document.documentElement.lang = locale;
}

export function t(key: MessageKey, values?: Record<string, string | number>): string {
  const message = messages[key][locale];
  return values ? message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder)) : message;
}
